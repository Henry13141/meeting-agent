export function meetingVideoExposure(clip: MeetingClip, mediaTime: number): number {
  const keys = EXPOSURE[clip === 'return-right' ? 'turn-right' : clip];
  if (!keys) return 1;
  const time = Number.isFinite(mediaTime) ? Math.max(0, mediaTime) : 0;
  const before = keys.findLast(([at]) => at <= time) ?? keys[0]!;
  const after = keys.find(([at]) => at > time) ?? before;
  const fraction = after === before ? 0 : (time - before[0]) / (after[0] - before[0]);
  return Number((before[1] + (after[1] - before[1]) * fraction).toFixed(4));
}
